test('drag extrusion, cancel/apply, redesigned cube, feature deletion and project deletion',async({page},testInfo)=>{
  await page.goto('/#projects')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByLabel('Project name',{exact:true}).fill('Manipulation verification')
  await page.getByRole('dialog',{name:'Create a new project'}).getByRole('button',{name:'Create project',exact:true}).click()
  await page.getByRole('button',{name:'Create sketch',exact:true}).click();await page.getByRole('button',{name:'Sketch on XY plane',exact:true}).click()
  await page.getByRole('button',{name:'Finish sketch',exact:true}).click()
  await page.getByRole('button',{name:'Extrude sketch',exact:true}).click()
  const handle=page.getByRole('button',{name:'Drag extrusion distance',exact:true})
  await expect(handle).toBeVisible()
  const box=await handle.boundingBox()
  await page.mouse.move(box!.x+box!.width/2,box!.y+box!.height/2)
  await page.mouse.down()
  await page.mouse.move(box!.x+box!.width/2,box!.y+box!.height/2-70,{steps:12})
  await page.mouse.up()
  await expect(page.getByText('FEATURE PREVIEW',{exact:true})).toBeVisible()
  expect(Number(await page.getByLabel('Distance',{exact:true}).inputValue())).toBeGreaterThan(16)
  await page.screenshot({path:testInfo.outputPath('extrusion-arrow.png')})
  await page.getByRole('button',{name:'Cancel',exact:true}).click()
  await expect(page.getByRole('button',{name:'Extrude sketch',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Extrude sketch',exact:true}).click()
  await handle.focus()
  await page.keyboard.press('ArrowUp')
  await expect(page.getByLabel('Distance',{exact:true})).toHaveValue('17')
  await expect(page.getByText('FEATURE PREVIEW',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Apply',exact:true}).click()
  await expect(page.getByTestId('model-volume')).toHaveText('25500.000 mm³')
  await page.getByRole('button',{name:'TOP',exact:true}).click()
  await expect(page.getByRole('button',{name:'TOP',exact:true})).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'Delete Sketch 1',exact:true}).click()
  const deletion=page.getByRole('dialog',{name:'Delete feature',exact:true})
  await expect(deletion.getByText('Extrude 1',{exact:true})).toBeVisible()
  await deletion.getByRole('button',{name:'Delete feature',exact:true}).click()
  await expect(page.getByRole('button',{name:'Create sketch',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(page.getByTestId('model-volume')).toHaveText('25500.000 mm³')
  await expect(page.getByText('Saved locally',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Manipulation verification',exact:true}).click()
  await page.getByRole('button',{name:'Delete project Manipulation verification',exact:true}).click()
  const projectDeletion=page.getByRole('dialog',{name:'Delete local project',exact:true})
  await projectDeletion.getByRole('button',{name:'Delete project',exact:true}).click()
  await expect(page.getByRole('heading',{name:'A clean slate.',exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading',{name:'A clean slate.',exact:true})).toBeVisible()
})